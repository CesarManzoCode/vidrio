#!/usr/bin/env python3
"""Generate crates/vjs/src/generated/unicode_id.rs from Unicode 17.0.0.

  python3 crates/vjs/gen/unicode.py

Downloads DerivedCoreProperties.txt of Unicode 17.0.0 to bench/cache/data/
(skipped when already there) and writes the ID_Start and ID_Continue tables
as sorted, merged ranges of code points (vault/CONTRACT.md §3.4, D-19).
Standard library only.
"""

import sys
import urllib.request
from pathlib import Path

VERSION = "17.0.0"
URL = f"https://www.unicode.org/Public/{VERSION}/ucd/DerivedCoreProperties.txt"
ROOT = Path(__file__).resolve().parents[3]
CACHE = ROOT / "bench" / "cache" / "data" / f"DerivedCoreProperties-{VERSION}.txt"
OUT = ROOT / "crates" / "vjs" / "src" / "generated" / "unicode_id.rs"
PROPERTIES = ("ID_Start", "ID_Continue")


def fetch():
    if CACHE.is_file():
        return CACHE.read_text(encoding="utf-8")
    CACHE.parent.mkdir(parents=True, exist_ok=True)
    with urllib.request.urlopen(URL, timeout=60) as response:
        data = response.read().decode("utf-8")
    first = data.splitlines()[0]
    if VERSION not in first:
        sys.exit(f"unexpected header in {URL}: {first!r}")
    CACHE.write_text(data, encoding="utf-8")
    return data


def parse(text):
    """Returns {property: [(first, last), ...]} for PROPERTIES."""
    ranges = {name: [] for name in PROPERTIES}
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        fields = [field.strip() for field in line.split(";")]
        if len(fields) < 2 or fields[1] not in ranges:
            continue
        if ".." in fields[0]:
            first, last = (int(part, 16) for part in fields[0].split(".."))
        else:
            first = last = int(fields[0], 16)
        ranges[fields[1]].append((first, last))
    return {name: merge(found) for name, found in ranges.items()}


def merge(ranges):
    merged = []
    for first, last in sorted(ranges):
        if merged and first <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(merged[-1][1], last))
        else:
            merged.append((first, last))
    return merged


def render(tables):
    lines = [
        f"//! ID_Start and ID_Continue of Unicode {VERSION}.",
        "//! Generated by crates/vjs/gen/unicode.py from DerivedCoreProperties.txt; do not edit.",
        "",
    ]
    for name in PROPERTIES:
        const = name.upper()
        lines.append(f"pub const {const}: &[(u32, u32)] = &[")
        for first, last in tables[name]:
            lines.append(f"    (0x{first:04X}, 0x{last:04X}),")
        lines.append("];")
        lines.append("")
    return "\n".join(lines)


def main():
    tables = parse(fetch())
    for name in PROPERTIES:
        if not tables[name]:
            sys.exit(f"no ranges found for {name}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(tables), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
