#!/usr/bin/env python3
"""Generate the UAX #9 tables of crates/vidrio/src/generated/bidi.rs.

  python3 crates/vidrio/gen/bidi.py

Downloads the Unicode 17.0.0 files BidiBrackets.txt and BidiMirroring.txt to
bench/cache/data/ (skipped when already there) and writes bidi.rs
(vault/CONTRACT.md D-19):

- BRACKETS: Bidi_Paired_Bracket and Bidi_Paired_Bracket_Type of every
  bracket, sorted by code point (rule N0).
- MIRRORING: Bidi_Mirroring_Glyph, sorted by code point (rule L4).

Bidi_Class itself is the table of crates/vidrio/gen/idna.py
(generated/idna.rs, BIDI_CLASS), shared to keep one copy. Standard library
only.
"""

import sys
import urllib.request
from pathlib import Path

VERSION = "17.0.0"
BASE = f"https://www.unicode.org/Public/{VERSION}/"
ROOT = Path(__file__).resolve().parents[3]
CACHE = ROOT / "bench" / "cache" / "data"
OUT = ROOT / "crates" / "vidrio" / "src" / "generated"

FILES = {
    "BidiBrackets": "ucd/BidiBrackets.txt",
    "BidiMirroring": "ucd/BidiMirroring.txt",
}


def fetch(name):
    path = CACHE / f"{name}-{VERSION}.txt"
    if not path.exists():
        CACHE.mkdir(parents=True, exist_ok=True)
        url = BASE + FILES[name]
        print(f"downloading {url}", file=sys.stderr)
        with urllib.request.urlopen(url) as response:
            data = response.read()
        tmp = path.with_suffix(".part")
        tmp.write_bytes(data)
        tmp.replace(path)
    return path.read_text(encoding="utf-8")


def data_lines(text):
    for line in text.split("\n"):
        line = line.split("#", 1)[0].strip()
        if line:
            yield [field.strip() for field in line.split(";")]


def brackets(text):
    """(code point, paired bracket, is_open) sorted by code point."""
    out = []
    for fields in data_lines(text):
        kind = fields[2]
        if kind not in ("o", "c"):
            raise SystemExit(f"unknown Bidi_Paired_Bracket_Type {kind!r}")
        out.append((int(fields[0], 16), int(fields[1], 16), kind == "o"))
    out.sort()
    return out


def mirroring(text):
    """(code point, mirrored glyph) sorted by code point."""
    out = sorted((int(f[0], 16), int(f[1], 16)) for f in data_lines(text))
    return out


def render(bracket_pairs, mirrors):
    lines = [
        f"//! UAX #9 data of Unicode {VERSION}: Bidi_Paired_Bracket(_Type) and",
        "//! Bidi_Mirroring_Glyph. Generated by crates/vidrio/gen/bidi.py from",
        "//! BidiBrackets.txt and BidiMirroring.txt; do not edit.",
        "",
        "/// (code point, paired bracket, opening) sorted by code point.",
        "pub const BRACKETS: &[(u32, u32, bool)] = &[",
    ]
    for cp, pair, opening in bracket_pairs:
        lines.append(f"    (0x{cp:04X}, 0x{pair:04X}, {'true' if opening else 'false'}),")
    lines.append("];")
    lines.append("")
    lines.append("/// (code point, Bidi_Mirroring_Glyph) sorted by code point.")
    lines.append("pub const MIRRORING: &[(u32, u32)] = &[")
    for cp, glyph in mirrors:
        lines.append(f"    (0x{cp:04X}, 0x{glyph:04X}),")
    lines.append("];")
    return lines


def main():
    bracket_pairs = brackets(fetch("BidiBrackets"))
    mirrors = mirroring(fetch("BidiMirroring"))
    OUT.mkdir(parents=True, exist_ok=True)
    path = OUT / "bidi.rs"
    path.write_text("\n".join(render(bracket_pairs, mirrors)) + "\n")
    print(f"wrote {path}", file=sys.stderr)


if __name__ == "__main__":
    main()
