#!/usr/bin/env python3
"""Generate the named character references of crates/vidrio/src/generated/.

  python3 crates/vidrio/gen/entities.py

Downloads https://html.spec.whatwg.org/entities.json to
bench/cache/data/entities.json (skipped when already there), checks its
sha256 against SHA256 (the download recorded in vault/RESEARCH.md) and
writes html_entities.rs (vault/CONTRACT.md D-19):

- ENTITIES: every name without its leading `&` (with the trailing `;` when
  the table has it), sorted by bytes, with its one or two code points; the
  second is 0 when the reference expands to a single code point.

The tokenizer walks the sorted table to find the longest name that is a
prefix of the input (HTML §13.2.5.73). Standard library only.
"""

import hashlib
import json
import sys
import urllib.request
from pathlib import Path

URL = "https://html.spec.whatwg.org/entities.json"
SHA256 = "d741d877ac77c4194c4ad526b5b4a19aef8dfe411ab840a466891cdbb9f362e6"
ROOT = Path(__file__).resolve().parents[3]
CACHE = ROOT / "bench" / "cache" / "data" / "entities.json"
OUT = ROOT / "crates" / "vidrio" / "src" / "generated"


def fetch():
    if not CACHE.exists():
        CACHE.parent.mkdir(parents=True, exist_ok=True)
        print(f"downloading {URL}", file=sys.stderr)
        with urllib.request.urlopen(URL) as response:
            data = response.read()
        tmp = CACHE.with_suffix(".json.part")
        tmp.write_bytes(data)
        tmp.replace(CACHE)
    data = CACHE.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SHA256:
        raise SystemExit(f"entities.json sha256 {digest} differs from the recorded {SHA256}")
    return json.loads(data.decode("utf-8"))


def entries(table):
    """(name without '&', first code point, second code point or 0), sorted by bytes."""
    out = []
    for name, value in table.items():
        assert name.startswith("&"), f"{name!r} does not start with '&'"
        points = value["codepoints"]
        assert 1 <= len(points) <= 2, f"{name!r} has {len(points)} code points"
        assert "".join(chr(p) for p in points) == value["characters"], name
        assert all(c.isascii() and (c.isalnum() or c == ";") for c in name[1:]), name
        out.append((name[1:], points[0], points[1] if len(points) == 2 else 0))
    out.sort(key=lambda e: e[0].encode("ascii"))
    return out


def render(items):
    lines = [
        "// Generated by crates/vidrio/gen/entities.py from",
        f"// {URL} (sha256 {SHA256}). Do not edit.",
        "",
        "/// Named character references of HTML §13.5: (name without `&`, first",
        "/// code point, second code point or 0), sorted by the bytes of the name.",
        "pub const ENTITIES: &[(&str, u32, u32)] = &[",
    ]
    for name, first, second in items:
        lines.append(f'    ("{name}", 0x{first:04X}, 0x{second:04X}),')
    lines.append("];")
    return lines


def main():
    items = entries(fetch())
    OUT.mkdir(parents=True, exist_ok=True)
    path = OUT / "html_entities.rs"
    path.write_text("\n".join(render(items)) + "\n")
    print(f"wrote {path} ({len(items)} entries)", file=sys.stderr)


if __name__ == "__main__":
    main()
