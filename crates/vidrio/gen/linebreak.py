#!/usr/bin/env python3
"""Generate the UAX #14 tables of crates/vidrio/src/generated/linebreak.rs.

  python3 crates/vidrio/gen/linebreak.py

Downloads the Unicode 17.0.0 files LineBreak.txt, EastAsianWidth.txt and
emoji-data.txt to bench/cache/data/ (skipped when already there) and writes
linebreak.rs (vault/CONTRACT.md D-19):

- LINE_BREAK: Line_Break of every code point as sorted ranges (the @missing
  default XX fills the gaps).
- EAST_ASIAN_WIDE: the code points whose East_Asian_Width is F, W or H
  (rules LB19a, LB30 and the segment break transformation of css-text-3).
- EXTENDED_PICTOGRAPHIC: the Extended_Pictographic ranges (rule LB30b).

General_Category comes from vjs's Unicode tables. Standard library only.
"""

import sys
import urllib.request
from pathlib import Path

VERSION = "17.0.0"
BASE = f"https://www.unicode.org/Public/{VERSION}/"
ROOT = Path(__file__).resolve().parents[3]
CACHE = ROOT / "bench" / "cache" / "data"
OUT = ROOT / "crates" / "vidrio" / "src" / "generated"
MAX = 0x10FFFF

FILES = {
    "LineBreak": "ucd/LineBreak.txt",
    "EastAsianWidth": "ucd/EastAsianWidth.txt",
    "emoji-data": "ucd/emoji/emoji-data.txt",
}

# The Line_Break values of Unicode 17.0.0, in the order of the constants.
CLASSES = [
    "XX", "AI", "AK", "AL", "AP", "AS", "B2", "BA", "BB", "BK", "CB", "CJ",
    "CL", "CM", "CP", "CR", "EB", "EM", "EX", "GL", "H2", "H3", "HH", "HL",
    "HY", "ID", "IN", "IS", "JL", "JT", "JV", "LF", "NL", "NS", "NU", "OP",
    "PO", "PR", "QU", "RI", "SA", "SG", "SP", "SY", "VF", "VI", "WJ", "ZW",
    "ZWJ",
]

WIDE = {"F", "W", "H"}


def fetch(name):
    path = CACHE / f"{name}-{VERSION}.txt"
    if not path.exists():
        CACHE.mkdir(parents=True, exist_ok=True)
        url = BASE + FILES[name]
        print(f"downloading {url}", file=sys.stderr)
        with urllib.request.urlopen(url) as response:
            data = response.read()
        tmp = path.with_suffix(".part")
        tmp.write_bytes(data)
        tmp.replace(path)
    return path.read_text(encoding="utf-8")


def code_range(field):
    field = field.strip()
    if ".." in field:
        first, last = field.split("..")
        return int(first, 16), int(last, 16)
    return int(field, 16), int(field, 16)


def data_lines(text):
    for line in text.split("\n"):
        line = line.split("#", 1)[0].strip()
        if line:
            yield [field.strip() for field in line.split(";")]


def property_ranges(text):
    """Sorted, merged (first, last, value) ranges of a property file with
    its @missing defaults applied first."""
    values = {}
    for line in text.split("\n"):
        if line.startswith("# @missing:"):
            body = line[len("# @missing:") :].split("#", 1)[0]
            field, value = [f.strip() for f in body.split(";")]
            first, last = code_range(field)
            for cp in range(first, last + 1):
                values[cp] = value
    for fields in data_lines(text):
        first, last = code_range(fields[0])
        for cp in range(first, last + 1):
            values[cp] = fields[1]
    return merge_values(values)


def merge_values(values):
    out = []
    for cp in sorted(values):
        value = values[cp]
        if out and out[-1][1] + 1 == cp and out[-1][2] == value:
            out[-1] = (out[-1][0], cp, value)
        else:
            out.append((cp, cp, value))
    return out


def ranges_of(text, wanted):
    """Merged (first, last) ranges whose value is in `wanted`."""
    out = []
    for first, last, value in property_ranges(text):
        if value not in wanted:
            continue
        if out and out[-1][1] + 1 == first:
            out[-1] = (out[-1][0], last)
        else:
            out.append((first, last))
    return out


def binary_ranges(text, name):
    """Merged ranges of a binary property listed in a data file."""
    cps = set()
    for fields in data_lines(text):
        if fields[1] == name:
            first, last = code_range(fields[0])
            cps.update(range(first, last + 1))
    out = []
    for cp in sorted(cps):
        if out and out[-1][1] + 1 == cp:
            out[-1] = (out[-1][0], cp)
        else:
            out.append((cp, cp))
    return out


def render(line_break, wide, pictographic):
    lines = [
        f"//! UAX #14 data of Unicode {VERSION}: Line_Break, the wide East_Asian_Width",
        "//! values and Extended_Pictographic. Generated by crates/vidrio/gen/linebreak.py",
        "//! from LineBreak.txt, EastAsianWidth.txt and emoji-data.txt; do not edit.",
        "",
    ]
    for i, name in enumerate(CLASSES):
        lines.append(f"pub const LB_{name}: u8 = {i};")
    lines.append("")
    lines.append("/// Line_Break of every code point, as sorted ranges.")
    lines.append("pub const LINE_BREAK: &[(u32, u32, u8)] = &[")
    for first, last, value in line_break:
        lines.append(f"    (0x{first:04X}, 0x{last:04X}, LB_{value}),")
    lines.append("];")
    lines.append("")
    lines.append("/// East_Asian_Width F, W or H, as sorted ranges.")
    lines.append("pub const EAST_ASIAN_WIDE: &[(u32, u32)] = &[")
    for first, last in wide:
        lines.append(f"    (0x{first:04X}, 0x{last:04X}),")
    lines.append("];")
    lines.append("")
    lines.append("/// Extended_Pictographic, as sorted ranges.")
    lines.append("pub const EXTENDED_PICTOGRAPHIC: &[(u32, u32)] = &[")
    for first, last in pictographic:
        lines.append(f"    (0x{first:04X}, 0x{last:04X}),")
    lines.append("];")
    return lines


def main():
    line_break = property_ranges(fetch("LineBreak"))
    covered = 0
    for first, last, value in line_break:
        if value not in CLASSES:
            raise SystemExit(f"unknown Line_Break value {value!r}")
        assert first == covered, f"LineBreak.txt leaves {covered:04X} out"
        covered = last + 1
    assert covered == MAX + 1, "LineBreak.txt does not reach U+10FFFF"
    wide = ranges_of(fetch("EastAsianWidth"), WIDE)
    pictographic = binary_ranges(fetch("emoji-data"), "Extended_Pictographic")
    OUT.mkdir(parents=True, exist_ok=True)
    path = OUT / "linebreak.rs"
    path.write_text("\n".join(render(line_break, wide, pictographic)) + "\n")
    print(f"wrote {path}", file=sys.stderr)


if __name__ == "__main__":
    main()
