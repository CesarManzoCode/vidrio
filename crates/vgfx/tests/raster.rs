#[test]
fn png_round_trip_keeps_every_pixel() {
    let (w, h) = (7u32, 5u32);
    let mut rgba = Vec::new();
    for y in 0..h {
        for x in 0..w {
            rgba.extend_from_slice(&[(x * 36) as u8, (y * 50) as u8, 200, 255 - (x * y) as u8]);
        }
    }
    let img = decode(&encode(w, h, &rgba, ColorType::Rgba)).expect("decodes");
    assert_eq!((img.width, img.height), (w, h));
    // Premultiplication loses precision only where alpha is below 255:
    // the round trip through straight alpha stays within one unit.
    let back = img.to_straight();
    for (i, (a, b)) in rgba.iter().zip(&back).enumerate() {
        assert!(a.abs_diff(*b) <= 1, "byte {i}: {a} vs {b}");
    }
    let rgb: Vec<u8> = (0..w * h * 3).map(|i| (i * 7) as u8).collect();
    let img = decode(&encode(w, h, &rgb, ColorType::Rgb)).expect("decodes");
    for (i, p) in img.data.chunks_exact(4).enumerate() {
        assert_eq!(&p[..3], &rgb[i * 3..i * 3 + 3]);
        assert_eq!(p[3], 255);
    }
}

#[test]
fn progressive_jpeg_matches_libjpeg() {
    let img = vgfx::image::decode(PROGRESSIVE_JPEG).expect("decodes");
    assert_eq!((img.width, img.height), (16, 16));
    let mut worst = 0u8;
    for y in 0..16u32 {
        for x in 0..16u32 {
            let p = img.pixel(x, y);
            assert_eq!(p[3], 255);
            let i = ((y * 16 + x) * 3) as usize;
            for k in 0..3 {
                worst = worst.max(p[k].abs_diff(DJPEG_RGB[i + k]));
            }
        }
    }
    assert!(worst <= 1, "largest difference from djpeg: {worst}");
    // And the picture is the gradient that was encoded.
    let p = img.pixel(15, 0);
    assert!(p[0] > 200 && p[1] < 40 && p[2].abs_diff(128) < 12, "{p:?}");
}

#[test]
fn pixel_aligned_box_with_solid_border_is_exact() {
    let mut pix = Pixmap::new(20, 20);
    let clip = Clip::full(20, 20);
    let blue = Paint::Solid([0, 0, 255, 255]);
    let red = Paint::Solid([255, 0, 0, 255]);
    // A 10×10 border box at (5, 5) with a 2px border, then its padding box.
    pix.fill_rect(&clip, 5.0, 5.0, 15.0, 15.0, &blue);
    pix.fill_rect(&clip, 7.0, 7.0, 13.0, 13.0, &red);
    for y in 0..20 {
        for x in 0..20 {
            let expected = if !(5..15).contains(&x) || !(5..15).contains(&y) {
                [0, 0, 0, 0]
            } else if (7..13).contains(&x) && (7..13).contains(&y) {
                [255, 0, 0, 255]
            } else {
                [0, 0, 255, 255]
            };
            assert_eq!(pix.pixel(x, y), expected, "pixel ({x}, {y})");
        }
    }
}

#[test]
fn even_odd_ring_and_rounded_corners() {
    let mut ring = vgfx::path::rect(0.0, 0.0, 10.0, 10.0);
    ring.segments
        .extend(vgfx::path::rect(2.0, 2.0, 8.0, 8.0).segments);
    let m = fill(&ring, FillRule::EvenOdd, (0, 0, 10, 10));
    assert_eq!(m.get(1, 1), 255);
    assert_eq!(m.get(5, 5), 0);
    let r = [(5.0, 5.0); 4];
    let m = fill(
        &vgfx::path::rounded_rect(0.0, 0.0, 10.0, 10.0, &r),
        FillRule::NonZero,
        (0, 0, 10, 10),
    );
    assert_eq!(m.get(0, 0), 0);
    assert_eq!(m.get(5, 5), 255);
    // The corner pixel next to the curve is partly covered.
    assert!(m.get(1, 1) > 0 && m.get(1, 1) < 255);
}
